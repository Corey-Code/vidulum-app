import fs from 'node:fs';
import path from 'node:path';

const OUT = path.resolve(__dirname, '..', 'src', 'lib', 'assets', 'chainRegistry.ts');

const header = `// AUTO-GENERATED by scripts/sync-chain-registry.ts — do not edit by hand.
`;

export function generateRegistry(entries: string[]): string {
  return `${header}export const CHAIN_REGISTRY = [
${entries.map((e) => `  ${e},`).join('\n')}
] as const;
`;
}

if (require.main === module) {
  const entries = JSON.parse(
    fs.readFileSync(path.resolve(__dirname, 'chain-registry.json'), 'utf8'),
  ) as string[];
  fs.writeFileSync(OUT, generateRegistry(entries));
  console.log(`Wrote ${entries.length} chains to ${OUT}`);
}
